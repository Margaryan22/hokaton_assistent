# Аббревиатуры раскрываются и в документах, и в запросах.
ABBREVIATIONS: dict[str, list[str]] = {
    "тз": ["технический", "задание"],
    "кп": ["коммерческий", "предложение"],
    "срм": ["crm"],
    "др": ["день", "рождение"],
}

SYNONYMS: dict[str, set[str]] = {}
for group in _GROUPS:
    for word in group:
        SYNONYMS.setdefault(word, set()).update(group - {word})


def expand_abbreviations(terms: list[str]) -> list[str]:
    out: list[str] = []
    for term in terms:
        out.extend(ABBREVIATIONS.get(term, [term]))
    return out
